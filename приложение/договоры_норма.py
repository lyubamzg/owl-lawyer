#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Нормализация и валидация видов договоров для конструктора «Сова-юрист».

Всё, что проверяет анкету до сборки .docx: обязательные поля по каждому виду,
правовые предупреждения (регистрация, беспроцентность, существенные условия).
Тексты самих договоров — в договоры_тексты.py (проверено 21.10.2026 по
действующей редакции ГК РФ от 24.06.2025: гл. 30/34/35/37/39/42 в 2025–2026
своими правками не менялись; порог 100 000 ₽ п. 4 ст. 809 живой).
"""
import re

# Вид договора → роли сторон (А = передающая сторона)
РОЛИ = {
    'Аренда жилого помещения':           ('Наймодатель', 'Наниматель'),
    'Аренда нежилого помещения':         ('Арендодатель', 'Арендатор'),
    'Купля-продажа движимого имущества': ('Продавец', 'Покупатель'),
    'Купля-продажа недвижимости':        ('Продавец', 'Покупатель'),
    'Подряд':                            ('Заказчик', 'Подрядчик'),
    'Возмездное оказание услуг':         ('Заказчик', 'Исполнитель'),
    'Заём':                              ('Заимодавец', 'Заёмщик'),
}

_ОРГ = ('ООО', 'ЗАO', 'ПАО', 'ОАО', 'АНО')


def пусто(v):
    return v is None or str(v).strip() == ''


def сумма(v):
    """Сумма как float или None («12 000руб» → 12000.0)."""
    m = re.search(r'[\d][\d\s.,]*', str(v or ''))
    if not m:
        return None
    s = m.group(0).replace(' ', '').replace(',', '.').rstrip('.')
    try:
        return float(s)
    except ValueError:
        return None


def дата_текст(v):
    if v is None or v == '':
        return ''
    if hasattr(v, 'strftime'):
        return v.strftime('%d.%m.%Y')
    return str(v).strip()


def оба_граждане(реквизиты):
    """Нет ли в реквизитах признаков юрлица/ИП (для правила п. 4 ст. 809)."""
    t = str(реквизиты or '').upper()
    return not any(token in t for token in _ОРГ + ('ИНН ', 'ОГРН'))


def проверить(строка, перечень=None):
    """строка — словарь «колонка → значение» одной строки листа «Договоры».

    перечень — построчный список листа «Перечень работ и услуг» (для подряда/услуг).
    Возвращает (ошибки, предупреждения): оба списка строк.
    """
    ошибки, предупреждения = [], []
    вид = str(строка.get('Вид договора') or '').strip()

    if пусто(вид):
        return ['вид договора не указан'], предупреждения
    if вид not in РОЛИ:
        return (['неизвестный вид договора «%s» — выберите один из: %s' % (вид, '; '.join(РОЛИ))],
                предупреждения)

    роль_а, роль_б = РОЛИ[вид]
    if пусто(строка.get('Сторона 1 (кто)')):
        ошибки.append('не указана сторона 1 (%s)' % роль_а)
    if пусто(строка.get('Сторона 2 (кто)')):
        ошибки.append('не указана сторона 2 (%s)' % роль_б)
    if пусто(строка.get('Предмет договора')):
        ошибки.append('не заполнен предмет договора')

    цена = сумма(строка.get('Цена (сумма), руб.'))
    if цена is None:
        ошибки.append('не указана цена (сумма) договора')

    if пусто(строка.get('Дата заключения')):
        ошибки.append('не указана дата заключения')

    срок_с = дата_текст(строка.get('Срок действия (с)'))
    срок_по = дата_текст(строка.get('Срок действия (по)'))

    # ─── Видоспецифичные проверки ────────────────────────────────────────────
    if вид == 'Аренда нежилого помещения' and срок_с and срок_по:
        предупреждения.append(
            'аренда нежилого помещения/здания на срок не менее года подлежит '
            'государственной регистрации (п. 2 ст. 651 ГК РФ) — не забудьте '
            'обратиться в Росреестр, иначе договор считается незаключённым')
    elif вид == 'Аренда нежилого помещения':
        предупреждения.append(
            'если срок аренды ≥ 1 года — регистрация в Росреестре '
            '(п. 2 ст. 651 ГК РФ); без срока договор считается бессрочным и '
            'расторгается уведомлением за 1 месяц (п. 2 ст. 610 ГК РФ)')

    if вид == 'Купля-продажа недвижимости':
        предупреждения.append(
            'право собственности к покупателю переходит только с '
            'государственной регистрацией в ЕГРН (п. 2 ст. 551 ГК РФ); '
            'составьте передаточный акт (п. 1 ст. 556 ГК РФ)')

    if вид.startswith('Купля-продажа') and пусто(строка.get('Порядок оплаты')):
        предупреждения.append(
            'порядок оплаты не заполнен — в текст попадёт нейтральная '
            'формулировка «оплата производится при подписании договора»')

    if вид == 'Подряд':
        if пусто(строка.get('Сроки выполнения работ (текст)')) and not (срок_с or срок_по):
            ошибки.append(
                'не указаны сроки выполнения работ — существенное условие '
                'договора подряда (абз. 2 п. 1 ст. 708 ГК РФ): заполните '
                '«Сроки выполнения работ (текст)» или даты действия')
        if пусто(перечень):
            предупреждения.append(
                'лист «Перечень работ и услуг» пуст — в договоре будет '
                'только текст предмета; желательно детализировать')

    if вид == 'Возмездное оказание услуг' and пусто(перечень):
        предупреждения.append(
            'лист «Перечень работ и услуг» пуст — услуги описаны только '
            'текстом предмета')

    if вид == 'Аренда жилого помещения' and пусто(строка.get('Коммунальные платежи (кто платит)')):
        предупреждения.append(
            'не указано, кто платит коммунальные — по умолчанию в тексте '
            'будет «коммунальные платежи оплачивает наниматель»')

    if вид == 'Заём':
        физ = оба_граждане(строка.get('Реквизиты стороны 1 (кто)')) and \
            оба_граждане(строка.get('Реквизиты стороны 2 (кто)'))
        проценты = str(строка.get('Проценты по займу (% год)') or '').strip()

        if физ and цена is not None and цена <= 100000:
            if не_проценты_указано(проценты):
                предупреждения.append(
                    'в договоре указаны проценты — беспроцентность п. 4 '
                    'ст. 809 ГК РФ (заём между гражданами до 100 000 ₽) '
                    'не применяется; стороны вправе договориться о '
                    'процентах — проверьте, что это осознанное решение')
            else:
                предупреждения.append(
                    'проценты не заполнены: заём между гражданами на '
                    '≤ 100 000 ₽ по п. 4 ст. 809 ГК РФ беспроцентный — '
                    'в тексте так и будет; чтобы назначить проценты, '
                    'заполните графу')
        elif пусто(проценты):
            предупреждения.append(
                'проценты не указаны — по п. 1 ст. 809 ГК РФ они '
                'начисляются по ключевой ставке Банка России; заполните '
                'графу, чтобы зафиксировать иной размер')

    return ошибки, предупреждения


def не_проценты_указано(текст):
    """Есть ли в поле процентов хоть что-то, кроме прочерка/«без»/«0»."""
    t = (текст or '').strip().lower().replace('%', '')
    if t in ('', '—', '-', '0', '0.0', 'нет', 'без'):
        return False
    m = re.search(r'(\d+(?:[.,]\d+)?)', t)
    if m and float(m.group(1).replace(',', '.')) == 0:
        return False
    return True