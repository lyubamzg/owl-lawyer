    if демо:
        for r in ДЕМО_ПЕРЕЧЕНЬ:
            ws.append(r)
    widths = (12, 8, 80)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[openpyxl.utils.get_column_letter(i)].width = w
    _заголовки(ws)

    # ────────────────────────────────────────────── график платежей ───────
    ws = wb.create_sheet('График платежей')
    ws.append(['№ договора', 'Дата платежа', 'Сумма, руб.', 'Назначение платежа'])
